const uint8_t* getFontData(char c) {
  if (c >= 'A' && c <= 'Z') return kFont[c - 'A'];
  if (c >= 'a' && c <= 'z') return kFont[c - 'a'];
  if (c >= '0' && c <= '9') return kFontDigits[c - '0'];
  switch (c) {
    case '-': return kFontDash;
    case '!': return kFontExcl;
    case '.': return kFontDot;
    case ':': return kFontColon;
    case '/': return kFontSlash;
    case '@': return kFontAt;
    case '+': return kFontPlus;
    default:  return nullptr;
  }
}

