void Scroller::reset(const char* text) {
  text_ = text;
  textLen_ = static_cast<int>(std::strlen(text));
  pos_ = 0.0f;
  time_ = 0.0f;
}

void Scroller::update(double dtSeconds, float speed) {
  pos_ += speed * static_cast<float>(dtSeconds) / static_cast<float>(kCharStride);
  if (pos_ >= static_cast<float>(textLen_)) {
    pos_ -= static_cast<float>(textLen_);
  }
  time_ += static_cast<float>(dtSeconds);
}

void Scroller::render(SDL_Renderer* renderer, int screenW, int screenH) const {
  const int numSlots = screenW / kCharStride + 1;
  const int baseY = (screenH * 4) / 5;

  for (int slot = 0; slot < numSlots; ++slot) {
    const int charIndex = (static_cast<int>(pos_) + slot) % textLen_;
    const char c = text_[charIndex];

    const int slotX = slot * kCharStride;
    const int y = baseY + static_cast<int>(24.0f * std::sin(static_cast<float>(slotX) * 0.025f + time_ * 2.5f));

    drawChar(renderer, c, slotX, y);
  }
}

void Scroller::drawChar(SDL_Renderer* renderer, char c, int x, int y) const {
  const uint8_t* data = getFontData(c);
  if (!data) return;

  for (int row = 0; row < 8; ++row) {
    uint8_t bits = data[row];
    int col = 0;
    while (bits && col < 8) {
      if (bits & 0x80) {
        int runEnd = col;
        while ((bits & 0x80) && runEnd < 8) {
          bits <<= 1;
          ++runEnd;
        }
        SDL_RenderDrawLine(renderer, x + col, y + row, x + runEnd - 1, y + row);
        col = runEnd;
      } else {
        bits <<= 1;
        ++col;
      }
    }
  }
}
